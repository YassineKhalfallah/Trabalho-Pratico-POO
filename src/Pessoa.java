public class Pessoa {
    protected String nomePessoa;
    public Pessoa(){};
    public Pessoa(String nomePessoa) {
        this.nomePessoa = nomePessoa;
    }
    public String getNomePessoa() {
        return nomePessoa;
    }
    public void setNomePessoa(String nomePessoa) {
        this.nomePessoa = nomePessoa;
    }
}
